-- CRIANDO A TABELA
CREATE TABLE USUARIO (
    IDUSUARIO INT NOT NULL AUTO_INCREMENT
    , NOME VARCHAR(100) NOT NULL
    , EMAIL VARCHAR(100)
    , SENHA VARCHAR(200)
    , PERFIL VARCHAR(10)
    , BLOQUEADO VARCHAR(1)
    , PRIMARY KEY (IDUSUARIO)
);

